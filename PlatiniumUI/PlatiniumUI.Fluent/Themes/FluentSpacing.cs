namespace PlatiniumUI.Fluent.Themes;

/// <summary>
/// Fluent Design System spacing and sizing tokens
/// Based on 4px grid system used in Microsoft Fluent Design
/// </summary>
public static class FluentSpacing
{
    // Spacing values (in device-independent pixels) - 4px grid
    public const double None = 0.0;
    public const double Xxs = 2.0;
    public const double Xs = 4.0;
    public const double S = 8.0;
    public const double M = 12.0;
    public const double Md = 16.0;
    public const double L = 20.0;
    public const double Xl = 24.0;
    public const double Xxl = 32.0;
    public const double Xxxl = 40.0;
    public const double Huge = 48.0;
    public const double Larger = 64.0;
    
    // Icon sizes
    public const double IconXs = 12.0;
    public const double IconS = 16.0;
    public const double IconM = 20.0;
    public const double IconL = 24.0;
    public const double IconXl = 32.0;
    public const double IconXxl = 48.0;
    
    // Control heights (Fluent standard control heights)
    public const double ControlHeightSmall = 32.0;
    public const double ControlHeightMedium = 40.0;
    public const double ControlHeightLarge = 48.0;
    
    // Border radius (corner radius)
    public const double RadiusNone = 0.0;
    public const double RadiusSmall = 2.0;
    public const double RadiusMedium = 4.0;
    public const double RadiusLarge = 6.0;
    public const double RadiusXl = 8.0;
    public const double RadiusXxl = 12.0;
    public const double RadiusFull = 9999.0; // Fully rounded
    
    // Elevation/Shadow depths (Fluent has 64 elevation levels, these are common ones)
    public const double Elevation0 = 0.0;     // No shadow
    public const double Elevation1 = 2.0;     // Subtle shadow
    public const double Elevation2 = 4.0;     // Low shadow
    public const double Elevation4 = 8.0;     // Medium shadow
    public const double Elevation8 = 16.0;    // High shadow
    public const double Elevation16 = 32.0;   // Very high shadow
    public const double Elevation24 = 48.0;   // Maximum shadow
}
